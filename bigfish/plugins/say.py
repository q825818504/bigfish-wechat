"""[插件] 说法 —— 让她像真人发微信，而不是发一段话。

为什么需要它
────────────
默认的模型输出是「一段完整的话」：四五十字、句号齐全、结构清楚。
那是写文章的习惯，不是发微信的习惯。真人发微信是：

    知道了
    那明天就去长坂坡玩吧
    咱们先看樱花，再看枣树

三条短句，每条都在等对方反应。一次塞完，读起来像通知。

这个插件管两件事：
  1. **告诉她怎么说**（这一段提示词）：短句优先、不总结、不列清单、
     想说的多就分条发。
  2. **给参数一个面板**：分几条、每条多长、条间等多久，
     都在插件页里调，不用改 config.json。

分条的**执行**在 `bigfish/say.py`（切分、节奏、发送确认），
这一段只负责让模型**本来就写成短句**——切是兜底，不是主要手段。

⚠ 这一段不决定「该不该回」。那是判定类插件的事。
"""
from __future__ import annotations

from typing import Any, Dict

from . import register

#: 分条标记。必须与 `bigfish.app.SPLIT_MARK` / `bigfish.say.SplitPolicy.marker` 一致。
_MARK = "{{split}}"


def _render(ctx: Dict[str, Any]) -> str:
    cfg = ctx.get("config") or {}
    max_parts = int(cfg.get("max_parts") or 4)
    part_chars = int(cfg.get("part_max_chars") or 50)
    lines = [
        "【像真人发微信】",
        f"- 一句话能说完就别用两句。超过 {part_chars} 字，先想能不能断开。",
        "- 不用「首先/其次/总之」，不列 1.2.3.，不写小标题，不用 Markdown。",
        "- 别人问什么答什么，不要先复述一遍再回答。",
        "- 语气词（嗯、啊、吧、呀）可以有，但不要每句都带。",
        f"- 想说的多就分条发，最多 {max_parts} 条：每条之间用单独一行 {_MARK} 断开。",
        f"  {_MARK} 是分条标记，不会发出去，也不要向对方解释它。",
        # 表情标记：以前「要不要配图」完全由系统掷骰子，模型想发也表达不了。
        # 这两个标记只是**表态**，真正发不发还要过插件开关、冷却和挑图。
        "- 这一句适合配张表情包时，可以在最前面写 [[sticker]]；不想配图就写 [[text]]。",
        "  [[sticker]] / [[text]] 也是给系统的标记，不会发出去。",
    ]
    return "\n".join(lines)


