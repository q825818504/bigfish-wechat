"""[插件] 余韵 —— 上一轮之后还留着什么。

为什么是 930
────────────
座位顺序决定语气：灵魂 860 立身份，生活 870 立处境，说法 890 定形式，
心情 900 给气氛，余韵 930 是"气氛之后还剩下的那点东西"。
放在心情后面，是因为它是心情的残留，不是心情本身；放在守卫 9990 前面，
因为它和心情一样属于资料，不能压过守卫。

为什么它可关，但关掉不等于她没脾气
──────────────────────────────
余韵的**状态**（afterglow.json）由核心写，关掉这个插件只是她不说、
不带着它说话。和「生活」同一个分层：

    bigfish/afterglow.py      状态机（器官）
    bigfish/plugins/afterglow.py  注入面（嘴）

关掉之后，情绪判断、衰减、软消照常发生 —— 只是下一轮提示词里
不再有「还留着的」那一段。这样用户想让她"不记仇"时有关可关，
但不会出现"关掉插件她连情绪都不动了"。

⚠ 不要在这里重新判断该不该生气
────────────────────────────
判定全在 afterglow.classify()，基于真实的心情差值。
这一层只负责把已有的余韵说清楚。在这里再判一次，
等于开了第二个真源 —— 两边迟早不一致。
"""
from __future__ import annotations

import time as _time
from typing import Any, Dict

from . import register


def _now_of(ctx: Dict[str, Any]) -> float:
    now = ctx.get("now")
    if isinstance(now, (int, float)):
        return float(now)
    return _time.time()


def _render(ctx: Dict[str, Any]) -> str:
    try:
        from bigfish import afterglow

        return afterglow.render(now=_now_of(ctx))
    except Exception:
        # 余韵读不出来不该让她失语。空串 = 这一段不出现。
        return ""


register(
    "afterglow",
    "余韵",
    "上一轮之后还留着的情绪——拌了嘴不会下一句就没事，被哄好了也不会立刻翻篇。",
    "prompt",
    order=930,
    default=True,
    why=(
        "没有它的时候，她只有「心情 58/100」这一个数。\n"
        "于是你刚跟她拌完嘴，下一句「在吗」，她用 58 分的语气正常回你——\n"
        "像什么都没发生过。分数能表达此刻，表达不了「刚才那件事」。\n"
        "打开后，一轮结束时如果情绪真的动了，会留下一条带由头的话：\n"
        "「刚才他说『你烦不烦』，你还没缓过来。」\n"
        "下一轮它会进提示词，几小时后自己淡掉；你道歉或示好，它会提前软下来。"
    ),
    affects=[
        "只在情绪真的动了的时候留（拌嘴、受伤、担心、被暖到），小波动不留",
        "冲突类留 4 小时、受伤 2 小时、担心 3 小时、暖意 1 小时",
        "你道歉/示好会软消，但还会留半小时「气消了但有点别扭」的尾韵",
        "同时最多三条，同类的只留最新一条",
        "会影响下一轮的表达预算：还在气头上时，她话更短、更容易不接",
    ],
    limits=[
        "不编由头：余韵里的引用来自你这一轮的原话，找不到就不引用",
        "不下结论：只写「他没回你」，不写「他不在乎你」",
        "不主动提：余韵是心里的余味，不是要拿出来讲的话",
        "关掉只是她不说，情绪状态照常记录和衰减",
    ],
    render=_render,
)
