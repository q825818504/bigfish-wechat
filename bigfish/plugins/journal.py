"""[插件] 日志 —— 每天睡前写一篇，存在本地。

为什么是 hook 类
────────────────
它不往提示词里加任何字，也不决定回不回。它只做一件事：
到点了，写一篇，存成文件。这正是 hook 的形态。

为什么不需要座位
────────────────
身份序是"提示词里按什么顺序排"。日记不进提示词
（理由见 bigfish/journal.py 的模块说明），所以不占位。
留一个空座位给一段永远不会出现的文字，只会让用户去翻一个空段。

它和「余韵」「日程」的区别
────────────────────────
那两个是**她说话时**的一段；这个是**她睡前**的一件事。
关掉它，她照常说话，只是不再写日记 —— 就像有人不写日记一样正常。

⚠ 日志不进提示词
────────────────
她"记得今天"靠的是记忆、心情、事实。真人也不会每天早上把昨天的
日记读一遍再开口。以后如果想让"她记得自己写过什么"，
正确做法是把日记的一句话摘要写进记忆库，而不是把全文注入。
"""
from __future__ import annotations

import time as _time
from typing import Any, Dict

from . import register


def _tick(ctx: Dict[str, Any]) -> None:
    world = ctx.get("world")
    if world is None:
        return
    now = ctx.get("now")
    if not isinstance(now, (int, float)):
        now = _time.time()
    world.tick_journal(float(now))


register(
    "journal",
    "日志",
    "每天睡前写一篇日记，存在本地——事情多就写长，没事就写两句，你自己打开就能看。",
    "hook",
    default=True,
    why=(
        "她没有「自己的东西」。所有产出都是**对你说的话**：\n"
        "回复、主动消息、道别。没有一句是写给她自己的。\n"
        "打开后，每天入睡前 20 分钟会写一篇日记，落在\n"
        "<数据根>/journal/YYYY-MM-DD.md，用记事本就能打开。\n"
        "长短跟着当天的事走：没事的日子几十字，有压在心上的事才写长。\n"
        "它不是总结，是「今天我是怎么过的」。"
    ),
    affects=[
        "每天一篇 Markdown 文件，一天一篇，同一天重写会覆盖",
        "用的是和复盘同一批素材：今天说过的话、心情起落、日程、关系事件",
        "字数按档位：空白日几十字，平常两三百字，有大事的那天才写到五六百以上",
        "会避开最近几篇的开头和道具，不连着几天写同一件事",
        "素材只有一句话时也会写——日记允许平淡",
        "写失败或没素材时，今天就不写，不会反复重试",
    ],
    limits=[
        "不进提示词：她不会因为写过日记就多知道什么",
        "不发微信、不通知你，只是安静地落在文件里",
        "不编：每个动作、每句话都要能在今天的素材里找到出处；连一句话都没有的那天，直接跳过",
        "同一句话不会出现两次——重复是生成痕迹，比写得短更伤真实感",
        "软上限 3000 字，超了截断——防模型复读，不是审美要求",
        "关掉它她照常说话，只是不再写日记",
    ],
    tick=_tick,
)
